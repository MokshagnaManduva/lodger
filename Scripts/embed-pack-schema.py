#!/usr/bin/env python3
"""Embed the normative schema for offline runtime validation; --check detects drift."""
import json
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
schema = json.loads((root / 'Schema/pack.schema.json').read_text())
keywords = {'$schema', '$id', '$defs', '$ref', 'title', 'description', 'default', 'format', 'type', 'required', 'additionalProperties', 'properties', 'oneOf', 'not', 'const', 'enum', 'pattern', 'minLength', 'maxLength', 'minimum', 'maximum', 'exclusiveMinimum', 'minProperties', 'minItems', 'uniqueItems', 'items'}
def visit(node):
    assert set(node) <= keywords, set(node) - keywords
    if '$ref' in node:
        assert node['$ref'].startswith('#/$defs/') and node['$ref'][8:] in schema['$defs']
    if 'format' in node: assert node['format'] == 'uri'
    if 'type' in node: assert node['type'] in {'object', 'array', 'string', 'integer', 'number', 'boolean'}
    for key in ('properties', '$defs'):
        for child in node.get(key, {}).values(): visit(child)
    for key in ('additionalProperties', 'items', 'not'):
        if isinstance(node.get(key), dict): visit(node[key])
    for child in node.get('oneOf', []): visit(child)
visit(schema)
text = '// Generated by Scripts/embed-pack-schema.py. Do not edit.\nimport Foundation\n\nenum PackSchema {\n    static let data = Data(#"""\n' + json.dumps(schema, separators=(',', ':'), ensure_ascii=True) + '\n"""#.utf8)\n}\n'
path = root / 'Engine/Sources/LodgerEngine/PackSchema.swift'
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != text:
        sys.exit('Embedded pack schema is stale; run python3 Scripts/embed-pack-schema.py')
else: path.write_text(text)
